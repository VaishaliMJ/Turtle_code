def main():
    timmyTurtle=Turtle()
    timmyTurtle.shape("turtle")
    timmyTurtle.color("blue")
    for cnt in range(4):
        timmyTurtle.forward(100)
        timmyTurtle.left(90)
    screen=Screen()
    screen.exitonclick()
