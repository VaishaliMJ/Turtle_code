def main():
    rgb_colors=[]
    colors=colorgram.extract("hist.jpg",30)
    for color in colors:
       r=color.rgb.r
       g=color.rgb.g
       b=color.rgb.b
       rgb_colors.append((r,g,b))
    print(rgb_colors)    
#####################################################################################################
#   Starter
#####################################################################################################
if __name__=="__main__":
    main()
