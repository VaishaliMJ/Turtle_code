def main():
    tim=t.Turtle()
    tim.speed("fastest")
    tim.hideturtle()
    t.colormode(255)
    tim.setheading(225)
    tim.penup()
    
    tim.forward(300)
    tim.setheading(0)
    numOfDots=100
    for cnt in range(1,numOfDots+1):
        tim.pendown()
        tim.dot(20,random.choice(color_list))
        tim.penup()
        tim.forward(50)

        if cnt % 10 ==0:
            tim.setheading(90)
            tim.forward(50)
            tim.setheading(180) 
            tim.forward(500)
            tim.setheading(0)   


    screen=t.Screen()
    screen.exitonclick()

